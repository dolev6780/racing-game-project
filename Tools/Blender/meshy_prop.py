"""
Turns a static prop generated by Meshy (a GLB, long axis along Blender's Z) into an FBX for Unity, sized and
placed so the game can hold it without adjusting it: its longest side becomes LENGTH metres, the point GRIP of
the way up from its lower end becomes the origin (where a hand holds it), and with --forward it is laid down to
point along Blender's -Y, which is Unity's +Z. --roll DEG then turns it about that long axis (a blade drawn
lying flat stands on its edge with --roll 90). --faces N simplifies it to about N triangles (for scenery
placed many times). Scenery uses GRIP 0: its foot is the origin.

    blender --background --python Tools/Blender/meshy_prop.py -- in.glb OUT_DIR NAME LENGTH GRIP [--forward] [--roll DEG] [--faces N]

Writes OUT_DIR/NAME.fbx and OUT_DIR/NAME_Albedo.png.
"""

import math
import os
import sys

import bpy
from mathutils import Matrix, Vector

args = sys.argv[sys.argv.index("--") + 1:]
src, out_dir, name, length, grip = args[0], args[1], args[2], float(args[3]), float(args[4])
forward = "--forward" in args
roll = float(args[args.index("--roll") + 1]) if "--roll" in args else 0.0
faces = int(args[args.index("--faces") + 1]) if "--faces" in args else 0

bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.gltf(filepath=src)
meshes = [o for o in bpy.data.objects if o.type == "MESH"]
for o in bpy.data.objects:
    o.select_set(o in meshes)
bpy.context.view_layer.objects.active = meshes[0]
if len(meshes) > 1:
    bpy.ops.object.join()
obj = bpy.context.view_layer.objects.active
bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
obj.name = obj.data.name = name
obj.data.calc_loop_triangles()
if 0 < faces < len(obj.data.loop_triangles):
    dec = obj.modifiers.new("simplify", "DECIMATE")
    dec.ratio = faces / len(obj.data.loop_triangles)
    bpy.ops.object.modifier_apply(modifier=dec.name)

pts = [v.co for v in obj.data.vertices]
lo = Vector([min(p[i] for p in pts) for i in range(3)])
hi = Vector([max(p[i] for p in pts) for i in range(3)])
k = length / max(hi - lo)
grip_z = lo.z + grip * (hi.z - lo.z)
centre = (lo + hi) / 2
m = Matrix.Scale(k, 4) @ Matrix.Translation(Vector((-centre.x, -centre.y, -grip_z)))
if forward:
    m = Matrix.Rotation(math.radians(90), 4, "X") @ m     # +Z (the far end) now points along -Y
m = Matrix.Rotation(math.radians(roll), 4, "Y" if forward else "Z") @ m
obj.data.transform(m)
obj.data.update()

os.makedirs(out_dir, exist_ok=True)
for mat in obj.data.materials:
    for n in (mat.node_tree.nodes if mat and mat.node_tree else []):
        if n.type == "BSDF_PRINCIPLED" and n.inputs["Base Color"].is_linked:
            img = n.inputs["Base Color"].links[0].from_node.image
            img.filepath_raw = os.path.join(out_dir, name + "_Albedo.png")
            img.file_format = "PNG"
            img.save()
fbx = os.path.join(out_dir, name + ".fbx")
bpy.ops.export_scene.fbx(filepath=fbx, use_selection=True, object_types={"MESH"}, bake_anim=False,
                         apply_scale_options="FBX_SCALE_ALL", mesh_smooth_type="FACE", path_mode="STRIP")
d = [round(v, 3) for v in obj.dimensions]
obj.data.calc_loop_triangles()
print(f"wrote {fbx}: {len(obj.data.loop_triangles)} triangles, size {d}")
